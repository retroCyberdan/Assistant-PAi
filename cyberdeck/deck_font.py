# Sostituzioni per caratteri tipografici comuni nelle risposte dell'AI
_SUBST = {
    "‘": "'", "’": "'", "“": '"', "”": '"',
    "–": "-", "—": "-", "…": "...", " ": " ",
    "•": "·", "×": "x", "−": "-", "\t": " ",
    "→": "->", "←": "<-", "«": '"', "»": '"',
}


def _parse(spec):
    rows = spec.split("|")
    bitmap = []
    for r in rows:
        bitmap.append([c == "#" for c in r])
    return bitmap


GLYPHS = {ch: _parse(spec) for ch, spec in _G.items()}
KANA = {ch: _parse(spec) for ch, spec in _K.items()}
GLYPHS.update(KANA)


def is_kana(ch):
    return ch in KANA


def normalize_text(text):
    """Converte il testo in caratteri disponibili nel font.

    Le lettere accentate non presenti vengono ridotte alla lettera base,
    le emoji e i simboli sconosciuti vengono rimossi.
    """
    out = []
    for ch in text or "":
        if ch == "\n":
            out.append(ch)
            continue
        if ch in GLYPHS:
            out.append(ch)
            continue
        if ch in _SUBST:
            out.append(_SUBST[ch])
            continue
        base = unicodedata.normalize("NFKD", ch)
        base = "".join(c for c in base if not unicodedata.combining(c))
        if base and all(c in GLYPHS for c in base):
            out.append(base)
        # altrimenti il carattere (es. emoji) viene scartato
    return "".join(out)


def glyph(ch):
    return GLYPHS.get(ch) or GLYPHS["?"]
